#!/usr/bin/env bash
# Rootless toolchain for hosts without Docker: install GnuCOBOL 3 and
# OpenJDK 21 from the official Ubuntu archive into a user-owned prefix.
#
#   bash scripts/wsl_toolchain.sh          # inside WSL (Ubuntu) or any Ubuntu
#   source ~/.local/cobalt-toolchain/env.sh
#
# Packages are fetched with `apt-get download` (no root needed) and unpacked
# with `dpkg -x`; nothing is installed system-wide. gcc must already exist
# because cobc compiles through C. -std=gnu17 is forced: GCC 15 defaults to
# C23, where the K&R prototypes cobc 3.2 emits for static CALLs break.
# The Docker image remains the reference environment; this exists so cobalt
# can run where Docker is unavailable.
set -euo pipefail

PREFIX="${COBALT_TOOLCHAIN:-$HOME/.local/cobalt-toolchain}"
DEBS="$PREFIX/debs"
PACKAGES=(
    gnucobol3 libcob4t64 libcob4-dev
    libgmp-dev libgmpxx4ldbl libgmp10
    libdb5.3t64 libjson-c5 libxml2-16 libncursesw6 libncurses6 libtinfo6
    openjdk-21-jre-headless openjdk-21-jdk-headless
    libjpeg-turbo8 libjpeg8 liblcms2-2 libnss3 libnspr4 libpcsclite1
)

command -v gcc >/dev/null || { echo "gcc is required (cobc compiles via C)" >&2; exit 1; }
mkdir -p "$DEBS" "$PREFIX/root"
cd "$DEBS"

for pkg in "${PACKAGES[@]}"; do
    status="$(dpkg-query -W -f='${Status}' "$pkg" 2>/dev/null || true)"
    if [[ "$status" == "install ok installed" ]]; then
        continue
    fi
    if ! ls "${pkg}"_*.deb >/dev/null 2>&1; then
        apt-get download -q "$pkg"
    fi
done

for deb in "$DEBS"/*.deb; do
    dpkg -x "$deb" "$PREFIX/root"
done

R="$PREFIX/root"
JAVA_HOME_DIR="$(ls -d "$R"/usr/lib/jvm/java-21-openjdk-* 2>/dev/null | head -1 || true)"
if [[ -z "$JAVA_HOME_DIR" ]]; then
    JAVA_HOME_DIR="$(ls -d /usr/lib/jvm/java-21-openjdk-* | head -1)"
fi
LIBDIR="$R/usr/lib/x86_64-linux-gnu"

cat > "$PREFIX/env.sh" <<EOF
# generated by scripts/wsl_toolchain.sh
export COBALT_TOOLCHAIN="$PREFIX"
export PATH="$R/usr/bin:$JAVA_HOME_DIR/bin:\$PATH"
export JAVA_HOME="$JAVA_HOME_DIR"
export LD_LIBRARY_PATH="$LIBDIR\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
export COB_CONFIG_DIR="$R/usr/share/gnucobol/config"
export COB_COPY_DIR="$R/usr/share/gnucobol/copy"
export COB_RUNTIME_CONFIG="$R/usr/share/gnucobol/config/runtime.cfg"
export COB_CFLAGS="-pipe -std=gnu17 -I$R/usr/include -I$R/usr/include/x86_64-linux-gnu -Wno-unused -fsigned-char -Wno-pointer-sign"
export COB_LDFLAGS="-L$LIBDIR -Wl,-rpath,$LIBDIR"
export COB_LIBS="-L$LIBDIR -lcob -lm -lgmp"
EOF

# shellcheck disable=SC1091
source "$PREFIX/env.sh"
cobc --version | head -1
java -version 2>&1 | head -1
echo "toolchain ready: source $PREFIX/env.sh"

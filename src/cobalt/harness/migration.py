# Tool implementations
# --------------------------------------------------------------------------- #
def _numbered(text: str) -> str:
    return "\n".join(f"{i:5}  {line}" for i, line in enumerate(text.splitlines(), start=1))


def _safe_rel(path: str) -> Path:
    rel = Path(path.replace("\\", "/"))
    if rel.is_absolute() or ".." in rel.parts:
        raise ToolError("paths must be relative to the workspace and must not contain '..'")
    return rel


def _layout_text(item: Any, indent: int = 0) -> list[str]:
    pic = f" PIC {item.picture}" if item.picture else ""
    usage = f" {item.usage}" if item.usage else ""
    occ = f" OCCURS {item.occurs}" if item.occurs else ""
    red = f" REDEFINES {item.redefines}" if item.redefines else ""
    sign = " SIGN LEADING SEPARATE" if item.sign_separate and item.sign_leading else ""
    line = (
        f"{' ' * indent}{item.level:02d} {item.name}{pic}{usage}{sign}{occ}{red}"
        f"  [offset {item.offset}, {item.total_size} bytes]"
    )
    out = [line]
    for name, value in item.conditions:
        out.append(f"{' ' * (indent + 4)}88 {name} VALUE {value}")
    for child in item.children:
        out.extend(_layout_text(child, indent + 4))
    return out


def format_report(report: EquivalenceReport, golden: GoldenStore, max_cases: int = 4) -> str:
    """Actionable equivalence feedback for an agent."""
    lines = [report.summary()]
    if not report.compile_ok:
        lines.append(report.compile_log[-3000:])
        return "\n".join(lines)
    shown = 0
    for case in report.cases:
        if case.passed or shown >= max_cases:
            continue
        shown += 1
        for stream in case.streams:
            if stream.ok or stream.first is None:
                if not stream.ok:
                    lines.append(f"  [{case.case}] {stream.name}: {stream.status}")
                continue
            d = stream.first
            lines.append(
                f"  [{case.case}] {stream.name}: {stream.differing_records} differing records "
                f"(expected {stream.expected_records}, got {stream.actual_records}); first at "
                f"record {d.record}, column {d.column}"
                + (
                    f", field {d.field} (offset {d.field_offset}, {d.field_size} bytes)"
                    if d.field
                    else ""
                )
            )
            lines.append(f"      expected: {d.expected!r}")
            lines.append(f"      actual:   {d.actual!r}")
        if case.error:
            lines.append(f"  [{case.case}] {case.error}")
        elif case.expected_rc != case.actual_rc:
            lines.append(f"  [{case.case}] exit code {case.actual_rc}, expected {case.expected_rc}")
    return "\n".join(lines)


def build_tools(ctx: MigrationContext) -> ToolRegistry:
    """All migration tools bound to ``ctx``. Roles take subsets."""
    spec = ctx.harness.spec
    search_dirs = list(spec.copybook_dirs) or copybook_search_dirs(
        ctx.settings.corpus_dir / ctx.corpus / "x", ctx.settings.corpus_dir / ctx.corpus
    )

    def read_cobol(args: ReadCobolIn) -> str:
        name = args.name.upper().removesuffix(".CBL").removesuffix(".CPY")
        path = ctx.program_path(name)
        if path is None:
            path = find_copybook(name, search_dirs)
        if path is None:
            raise ToolError(f"no program or copybook named {name} in corpus {ctx.corpus}")
        text = path.read_text(encoding="latin-1")
        return _numbered(text) if args.line_numbers else text

    def query_graph(args: QueryGraphIn) -> str:
        if not ctx.use_graph:
            raise ToolError("the knowledge graph is disabled for this run")
        name = args.name.upper()
        if args.kind == "context":
            return json.dumps(context_for(ctx.graph, name), indent=1)
        if args.kind == "order":
            return "\n".join(
                f"wave {e.wave}: {e.program} depends on {e.depends_on}"
                for e in migration_order(ctx.graph)
            )
        if args.kind == "callers":
            cg = call_graph(ctx.graph)
            return ", ".join(sorted(cg.predecessors(name))) if name in cg else "(none)"
        if args.kind == "impact":
            return ", ".join(impact(ctx.graph, name)) or "(nothing)"
        prog, _, item = name.rpartition(":")
        prog = prog or ctx.program
        path = ctx.program_path(prog)
        if path is None:
            raise ToolError(f"unknown program {prog}")
        parsed = parse_program(path, search_dirs)
        found = parsed.find_item(item)
        if found is None:
            raise ToolError(f"no data item {item} in {prog}")
        return "\n".join(_layout_text(found))

    def list_files(args: ListIn) -> str:
        base = ctx.workspace / _safe_rel(args.directory or ".")
        if not base.is_dir():
            raise ToolError(f"no directory {args.directory}")
        files = sorted(
            p.relative_to(ctx.workspace).as_posix() for p in base.rglob("*") if p.is_file()
        )
        return "\n".join(files) or "(empty)"

    def read_file(args: PathIn) -> str:
        rel = _safe_rel(args.path)
        if rel.parts and rel.parts[0] == "runtime":
            path = ctx.settings.root / "java-runtime" / Path(*rel.parts[1:])
        else:
            path = ctx.workspace / rel
        if not path.is_file():
            raise ToolError(f"no file {args.path}")
        return path.read_text(encoding="utf-8", errors="replace")

    def write_file(args: WriteFileIn) -> str:
        rel = _safe_rel(args.path)
        allowed = [JAVA_SRC / java_package_dir(p) for p in ctx.writable_programs]
        is_java = rel.suffix == ".java" and any(rel.is_relative_to(a) for a in allowed)
        is_case = (
            ctx.allow_cases
            and len(rel.parts) == 4
            and rel.parts[0] == "cases"
            and rel.parts[1] == ctx.program
            and _CASE_NAME.match(rel.parts[2]) is not None
            and ctx.has_run_spec
            and rel.parts[3] in spec.program(ctx.program).inputs
        )
        if not (is_java or is_case):
            targets = ", ".join(a.as_posix() + "/" for a in allowed)
            raise ToolError(
                f"writes are allowed only under {targets}"
                + (f" and cases/{ctx.program}/<case>/<INPUT>" if ctx.allow_cases else "")
            )
        path = ctx.workspace / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if is_case:
            path.write_bytes(args.content.encode("latin-1", errors="replace"))
        else:
            path.write_text(args.content, encoding="utf-8")
        ctx.files_written.append(rel.as_posix())
        return f"wrote {rel.as_posix()} ({len(args.content)} chars)"

    def compile_java(_: NoArgs) -> str:
        result = ctx.harness.compile_java(ctx.program, ctx.workspace, ctx.dependencies)
        if result.ok:
            return "compiled OK"
        if result.errors:
            errs = "\n".join(f"{e['file']}:{e['line']}: {e['message']}" for e in result.errors[:25])
            raise ToolError(
                f"compilation failed ({len(result.errors)} errors):\n{errs}\n\n{result.log[-2500:]}"
            )
        raise ToolError(f"compilation failed:\n{result.log[-3000:]}")

    def capture_golden(_: NoArgs) -> str:
        if not ctx.has_run_spec:
            raise ToolError(f"{ctx.program} has no run spec (it is a subprogram)")
        results = ctx.harness.capture_golden(
            ctx.program, extra_roots=[ctx.cases_root], store=ctx.golden
        )
        return "\n".join(f"{r.case}: {r.status} rc={r.returncode}" for r in results)

    def run_equivalence(args: CaseIn) -> ToolReply:
        if not ctx.has_run_spec:
            compile_java(NoArgs())
            note = (
                f"{ctx.program} is a subprogram with no standalone test; it is verified "
                f"through its callers ({', '.join(ctx.callers) or 'none'}). It compiles."
            )
            return ToolReply(note, {"passed": None})
        if ctx.allow_cases and (ctx.cases_root / ctx.program).is_dir():
            ctx.harness.capture_golden(ctx.program, extra_roots=[ctx.cases_root], store=ctx.golden)
        report = ctx.harness.check(
            ctx.program,
            ctx.workspace,
            dependencies=ctx.dependencies,
            extra_roots=[ctx.cases_root] if ctx.allow_cases else [],
            store=ctx.golden,
            cases=[args.case] if args.case else None,
        )
        if args.case is None:
            ctx.last_report = report
        return ToolReply(format_report(report, ctx.golden), {"passed": report.passed})

    def show_golden(args: ShowIn) -> str:
        g = ctx.golden.load(ctx.program, args.case)
        if g is None:
            raise ToolError(f"no golden output for case {args.case}")
        data = (
            g.output.stdout
            if args.stream.upper() == "SYSOUT"
            else g.output.files.get(args.stream.upper())
        )
        if data is None:
            return f"(stream {args.stream} was not produced by the COBOL program)"
        text = data.decode("latin-1") if isinstance(data, bytes) else data
        lines = text.splitlines()
        start = max(1, args.start)
        chunk = lines[start - 1 : start - 1 + min(args.count, 200)]
        body = "\n".join(f"{i:5}|{line}" for i, line in enumerate(chunk, start=start))
        return f"{args.stream} ({len(lines)} records, rc={g.output.returncode}):\n{body}"

    def show_input(args: ShowIn) -> str:
        cases = {c.name: c for c in ctx.harness.cases(ctx.program, [ctx.cases_root])}
        case = cases.get(args.case)
        if case is None:
            raise ToolError(f"no case {args.case}; cases: {', '.join(cases)}")
        path = case.inputs.get(args.stream.upper())
        if path is None:
            raise ToolError(f"case inputs are {', '.join(case.inputs)}")
        lines = path.read_text(encoding="latin-1").splitlines()
        start = max(1, args.start)
        chunk = lines[start - 1 : start - 1 + min(args.count, 200)]
        return "\n".join(f"{i:5}|{line}" for i, line in enumerate(chunk, start=start))

    def list_cases(_: NoArgs) -> str:
        if not ctx.has_run_spec:
            return "(subprogram: no test cases)"
        cases = ctx.harness.cases(ctx.program, [ctx.cases_root] if ctx.allow_cases else [])
        return "\n".join(f"{c.name} ({c.source}): " + ", ".join(sorted(c.inputs)) for c in cases)

    def get_summary(args: SummaryIn) -> str:
        if ctx.summaries is None:
            raise ToolError("module summaries are not available in this run")
        text = ctx.summaries.get(args.program.upper())
        if not text:
            raise ToolError(f"no summary for {args.program} (not migrated yet?)")
        return text

    def finish(args: FinishIn) -> ToolReply:
        if not args.success:
            return ToolReply(
                "acknowledged: migration not completed",
                {"success": False, "summary": args.summary},
                terminal=True,
            )
        if ctx.has_run_spec:
            reply = run_equivalence(CaseIn(case=None))
            report = ctx.last_report
            if report is None or not report.passed:
                raise ToolError(
                    "cannot finish with success: equivalence is not passing.\n" + reply.text
                )
            detail = report.summary()
        else:
            compile_java(NoArgs())
            detail = f"{ctx.program}: compiles (verified through callers)"
        return ToolReply(
            f"accepted: {detail}",
            {"success": True, "summary": args.summary, "verdict": detail},
            terminal=True,
        )

    tools = [
        Tool(
            "read_cobol",
            "Read the COBOL source of a program or copybook in the corpus.",
            ReadCobolIn,
            read_cobol,
        ),
        Tool(
            "query_graph",
            "Ask the code knowledge graph about programs, copybooks, files and record layouts.",
            QueryGraphIn,
            query_graph,
        ),
        Tool("list_files", "List files in the migration workspace.", ListIn, list_files),
        Tool(
            "read_file",
            "Read a workspace file (Java you or earlier modules wrote, test "
            "cases) or the shared runtime under runtime/src/main/java/...",
            PathIn,
            read_file,
        ),
        Tool(
            "write_file",
            "Create or replace a Java source file of the module (or a test case input file).",
            WriteFileIn,
            write_file,
        ),
        Tool(
            "compile_java",
            "Compile the module's Java (with its callees and the runtime) in the sandbox.",
            NoArgs,
            compile_java,
        ),
        Tool(
            "run_equivalence",
            "Run the Java on every test case and diff against the COBOL golden outputs.",
            CaseIn,
            run_equivalence,
        ),
        Tool("list_cases", "List the module's test cases and their inputs.", NoArgs, list_cases),
        Tool("show_golden", "Show lines of a golden (expected) output.", ShowIn, show_golden),
        Tool("show_input", "Show lines of a test case input file.", ShowIn, show_input),
        Tool(
            "capture_golden",
            "Run the original COBOL on the module's test cases (including "
            "new ones you wrote under cases/) to record golden outputs.",
            NoArgs,
            capture_golden,
        ),
        Tool(
            "get_summary",
            "Get the folded summary of an already migrated module "
            "(interface, layouts, behaviour, pitfalls).",
            SummaryIn,
            get_summary,
        ),
        Tool(
            "finish",
            "End the task. With success=true the harness re-runs equivalence and "
            "only accepts a passing migration.",
            FinishIn,
            finish,
        ),
    ]
    return ToolRegistry(tools)


def describe_module(ctx: MigrationContext) -> dict[str, Any]:
    """Facts for the task prompt."""
    node = ctx.graph.nodes.get(program_id(ctx.program), {})
    info: dict[str, Any] = {
        "program": ctx.program,
        "source": node.get("path"),
        "main_class": main_class(ctx.program),
        "package_dir": (JAVA_SRC / java_package_dir(ctx.program)).as_posix(),
        "kind": "main program" if ctx.has_run_spec else "called subprogram",
        "dependencies": [
            {
                "program": d,
                "java_class": main_class(d),
                "package_dir": (JAVA_SRC / java_package_dir(d)).as_posix(),
            }
            for d in ctx.dependencies
        ],
        "callers": ctx.callers,
    }
    if ctx.has_run_spec:
        prog = ctx.harness.spec.program(ctx.program)
        info["inputs"] = sorted(prog.inputs)
        info["outputs"] = list(prog.outputs)
        info["stdout_compared"] = prog.stdout
        info["cases"] = [c.name for c in ctx.harness.cases(ctx.program, [ctx.cases_root])]
    return info

"""The migration workspace and the tools agents use inside it.

One migration *run* owns ``workspace/<run_id>/``, a Maven-layout project
shared by every module in the run - so a caller's Java can use the already
migrated Java of its callees, which is why migration order matters.

Agents never touch the host directly: reads are limited to the corpus and
the workspace, writes to the packages of the module being migrated (and its
callees), and every compile/run goes through the sandbox.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

import networkx as nx
from pydantic import Field

from cobalt.config import Settings
from cobalt.equivalence.golden import GoldenStore, LayeredGoldenStore
from cobalt.equivalence.harness import EquivalenceHarness, EquivalenceReport
from cobalt.equivalence.runtime import java_package_dir, main_class
from cobalt.graph.build import program_id
from cobalt.graph.parser import copybook_search_dirs, parse_program
from cobalt.graph.query import call_graph, context_for, impact, migration_order
from cobalt.graph.source import find_copybook
from cobalt.harness.tools import Tool, ToolError, ToolInput, ToolRegistry, ToolReply

JAVA_SRC = Path("src/main/java")
_CASE_NAME = re.compile(r"^[a-z0-9][a-z0-9-]{0,40}$")
POM = """<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by cobalt. The harness compiles with javac in the sandbox; the
     shared runtime lives in java-runtime/ at the repository root. -->
<project xmlns="http://maven.apache.org/POM/4.0.0">
  <modelVersion>4.0.0</modelVersion>
  <groupId>cobalt.migrated</groupId>
  <artifactId>{artifact}</artifactId>
  <version>0.1.0</version>
  <properties>
    <maven.compiler.release>21</maven.compiler.release>
    <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>
  </properties>
</project>
"""


@dataclass
class MigrationContext:
    """Everything the tools need for one module of one run."""

    settings: Settings
    corpus: str
    run_id: str
    program: str
    harness: EquivalenceHarness
    graph: nx.MultiDiGraph
    use_graph: bool = True
    allow_cases: bool = True
    dependencies: list[str] = field(default_factory=list)
    callers: list[str] = field(default_factory=list)
    summaries: Any = None  # memory store (Stage 6); exposes .get(program) -> str | None
    last_report: EquivalenceReport | None = None
    files_written: list[str] = field(default_factory=list)

    @property
    def workspace(self) -> Path:
        return self.settings.workspace_dir / self.run_id

    @property
    def has_run_spec(self) -> bool:
        return self.program in self.harness.spec.programs

    @property
    def cases_root(self) -> Path:
        return self.workspace / "cases"

    @property
    def golden(self) -> GoldenStore:
        return LayeredGoldenStore([GoldenStore(self.workspace / "golden"), self.harness.golden])

    @property
    def writable_programs(self) -> list[str]:
        return [self.program, *self.dependencies]

    def ensure_workspace(self) -> None:
        (self.workspace / JAVA_SRC).mkdir(parents=True, exist_ok=True)
        pom = self.workspace / "pom.xml"
        if not pom.exists():
            pom.write_text(POM.format(artifact=f"{self.corpus}-{self.run_id}"), encoding="utf-8")

    def program_path(self, name: str) -> Path | None:
        node = self.graph.nodes.get(program_id(name.upper()))
        if node and node.get("path"):
            return self.settings.root / node["path"]
        return None


def for_program(
    settings: Settings,
    corpus: str,
    run_id: str,
    program: str,
    harness: EquivalenceHarness,
    graph: nx.MultiDiGraph,
    **kwargs: Any,
) -> MigrationContext:
    """Build a context, filling dependencies and callers from the graph."""
    order = {e.program: e for e in migration_order(graph)}
    cg = call_graph(graph)
    ctx = MigrationContext(
        settings,
        corpus,
        run_id,
        program.upper(),
        harness,
        graph,
        dependencies=order[program.upper()].depends_on if program.upper() in order else [],
        callers=sorted(cg.predecessors(program.upper())) if program.upper() in cg else [],
        **kwargs,
    )
    ctx.ensure_workspace()
    return ctx


# --------------------------------------------------------------------------- #
# Tool inputs
# --------------------------------------------------------------------------- #
class ReadCobolIn(ToolInput):
    name: str = Field(description="Program name (e.g. INTCALC) or copybook name (e.g. ACCTREC).")
    line_numbers: bool = Field(description="Prefix each line with its line number.")


class QueryGraphIn(ToolInput):
    kind: Literal["context", "layout", "callers", "impact", "order"] = Field(
        description=(
            "context: files, copybooks, callees and parameters of a program; "
            "layout: byte layout of a record/group (name = PROGRAM:ITEM or ITEM); "
            "callers: programs calling a program; impact: what a change affects; "
            "order: migration order of the corpus."
        )
    )
    name: str = Field(description="Program, copybook, file or PROGRAM:ITEM; ignored for order.")


class PathIn(ToolInput):
    path: str = Field(
        description="Path relative to the workspace root, or runtime/... for the "
        "shared Java runtime."
    )


class ListIn(ToolInput):
    directory: str = Field(description="Directory relative to the workspace root ('' = root).")


class WriteFileIn(ToolInput):
    path: str = Field(
        description="Workspace-relative path, e.g. "
        "src/main/java/cobalt/migrated/custrpt/Custrpt.java or "
        "cases/CUSTRPT/my-case/CUSTIN."
    )
    content: str = Field(description="Full file content (the file is replaced).")


class NoArgs(ToolInput):
    pass


class CaseIn(ToolInput):
    case: str | None = Field(description="Run only this test case (null = all cases).")


class ShowIn(ToolInput):
    case: str = Field(description="Test case name, e.g. default.")
    stream: str = Field(description="Logical file name (e.g. RPTOUT) or SYSOUT for stdout.")
    start: int = Field(description="First line to show (1-based).")
    count: int = Field(description="Number of lines (max 200).")


class FinishIn(ToolInput):
    success: bool = Field(description="True only if the migration is complete and equivalent.")
    summary: str = Field(description="What was done, key decisions, and any known risks.")


class SummaryIn(ToolInput):
    program: str = Field(description="An already migrated program.")


